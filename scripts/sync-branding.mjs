#!/usr/bin/env node
/**
 * Publishes branding pack assets from ./branding → ./public/brand
 * and generates src/lib/brand.generated.ts + src/brand/tokens.css + src/brand/fonts.css
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = path.join(ROOT, "branding");
const OUT_DIR = path.join(ROOT, "public", "brand");
const GEN_TS = path.join(ROOT, "src", "lib", "brand.generated.ts");
const GEN_CSS = path.join(ROOT, "src", "brand", "tokens.css");
const GEN_FONTS = path.join(ROOT, "src", "brand", "fonts.css");

const SKIP_EXT = new Set([".md", ".txt", ".pdf", ".docx"]);
const LOGO_PATTERNS = [
  /^logo\.(svg|png|webp)$/i,
  /^signet[-_ ]?logo\.(svg|png|webp)$/i,
  /logo.*signet.*\.(svg|png|webp)$/i,
  /signet.*logo.*\.(svg|png|webp)$/i,
];
const MARK_PATTERNS = [
  /^logo-mark\.(svg|png|webp)$/i,
  /^mark\.(svg|png|webp)$/i,
  /^icon\.(svg|png|webp)$/i,
  /^favicon\.(svg|png|webp)$/i,
  /^app-icon\.(svg|png|webp)$/i,
];
const WORDMARK_PATTERNS = [
  /^wordmark\.(svg|png|webp)$/i,
  /^signet[-_ ]?wordmark\.(svg|png|webp)$/i,
];
const TOKEN_FILES = ["brand-tokens.json", "colors.json", "tokens.json", "brand.json"];
const FONT_EXT = new Set([".woff2", ".woff", ".ttf", ".otf"]);

const GOOGLE_FONTS = {
  "Playfair Display": "Playfair+Display:ital,wght@0,400;0,500;0,600;0,700;1,400",
  "Space Grotesk": "Space+Grotesk:wght@400;500;600;700",
  Inter: "Inter:wght@300;400;500;600;700",
  "JetBrains Mono": "JetBrains+Mono:wght@400;500;600",
  Cormorant: "Cormorant+Garamond:ital,wght@0,400;0,500;0,600;0,700;1,400",
  "Cormorant Garamond": "Cormorant+Garamond:ital,wght@0,400;0,500;0,600;0,700;1,400",
};

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir)) {
    if (name === "README.md") continue;
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) walk(full, out);
    else if (!SKIP_EXT.has(path.extname(name).toLowerCase())) out.push(full);
  }
  return out;
}

function matchName(file, patterns) {
  const base = path.basename(file);
  return patterns.some((re) => re.test(base));
}

function pickBest(files, patterns) {
  const hits = files.filter((f) => matchName(f, patterns));
  if (!hits.length) return null;
  hits.sort((a, b) => {
    const score = (f) =>
      (f.endsWith(".svg") ? 0 : 1) +
      (/(primary|main|full)/i.test(f) ? -0.5 : 0) +
      f.length * 0.001;
    return score(a) - score(b);
  });
  return hits[0];
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function copyFile(src, destName) {
  const dest = path.join(OUT_DIR, destName);
  fs.copyFileSync(src, dest);
  return `/brand/${destName}`;
}

function readJsonTokens(files) {
  for (const name of TOKEN_FILES) {
    const hit = files.find((f) => path.basename(f).toLowerCase() === name.toLowerCase());
    if (!hit) continue;
    try {
      return JSON.parse(fs.readFileSync(hit, "utf8"));
    } catch (e) {
      console.warn(`Could not parse ${hit}:`, e.message);
    }
  }
  return null;
}

function cssVar(name, value) {
  if (!value || typeof value !== "string") return "";
  return `  --color-${name}: ${value};`;
}

function writeCss(tokens) {
  ensureDir(path.dirname(GEN_CSS));
  const colors = tokens?.colors ?? {};
  const lines = [
    "/* Auto-generated by npm run brand:sync — do not edit */",
    ":root {",
    cssVar("bg", colors.bg),
    cssVar("bg-alt", colors.bgAlt ?? colors["bg-alt"]),
    cssVar("surface", colors.surface),
    cssVar("surface-raised", colors.surfaceRaised ?? colors["surface-raised"]),
    cssVar("gold", colors.gold),
    cssVar("gold-light", colors.goldLight ?? colors["gold-light"]),
    cssVar("gold-bright", colors.goldBright ?? colors["gold-bright"]),
    cssVar("gold-muted", colors.goldMuted ?? colors["gold-muted"]),
    cssVar("gold-dim", colors.goldDim ?? colors["gold-dim"]),
    cssVar("ink", colors.ink ?? colors.text),
    cssVar("ink-muted", colors.inkMuted ?? colors.muted ?? colors["ink-muted"]),
    cssVar("ink-dim", colors.inkDim ?? colors["ink-dim"]),
    cssVar("burgundy", colors.burgundy),
    cssVar("burgundy-bright", colors.burgundyBright ?? colors["burgundy-bright"]),
    cssVar("burgundy-dark", colors.burgundyDark ?? colors["burgundy-dark"]),
  ].filter(Boolean);
  lines.push("}");

  if (colors.gold && colors.goldBright) {
    lines.push(
      "",
      ":root {",
      `  --gold-gradient: linear-gradient(135deg, ${colors.gold} 0%, ${colors.goldBright ?? colors.gold} 50%, ${colors.gold} 100%);`,
      "}",
    );
  }

  fs.writeFileSync(GEN_CSS, lines.join("\n") + "\n");
}

function writeFontsCss(tokens, localFonts) {
  ensureDir(path.dirname(GEN_FONTS));
  const fonts = tokens?.fonts ?? {};
  const families = new Set(
    [fonts.display, fonts.heading, fonts.body, fonts.mono].filter(Boolean),
  );

  const googleParams = [...families]
    .map((f) => GOOGLE_FONTS[f])
    .filter(Boolean);

  const lines = ["/* Auto-generated by npm run brand:sync — do not edit */"];

  if (googleParams.length) {
    lines.push(`@import url('https://fonts.googleapis.com/css2?${googleParams.map((p) => `family=${p}`).join("&")}&display=swap');`);
  }

  for (const lf of localFonts) {
    const ext = path.extname(lf.file).toLowerCase();
    const format =
      ext === ".woff2" ? "woff2" : ext === ".woff" ? "woff" : ext === ".otf" ? "opentype" : "truetype";
    lines.push(`@font-face {
  font-family: "${lf.family}";
  src: url("${lf.url}") format("${format}");
  font-display: swap;
}`);
  }

  if (fonts.display) lines.push(`\n:root { --font-display: "${fonts.display}", Georgia, serif; }`);
  if (fonts.heading) lines.push(`:root { --font-heading: "${fonts.heading}", system-ui, sans-serif; }`);
  if (fonts.body) lines.push(`:root { --font-body: "${fonts.body}", system-ui, sans-serif; }`);
  if (fonts.mono) lines.push(`:root { --font-mono: "${fonts.mono}", ui-monospace, monospace; }`);

  fs.writeFileSync(GEN_FONTS, lines.join("\n") + "\n");
}

function writeTs(manifest) {
  const body = `// Auto-generated by npm run brand:sync — do not edit
export const brandAssets = ${JSON.stringify(manifest, null, 2)} as const;
`;
  fs.writeFileSync(GEN_TS, body);
}

function main() {
  if (!fs.existsSync(SRC_DIR)) {
    console.error("Missing branding/ folder.");
    process.exit(1);
  }

  const files = walk(SRC_DIR);
  const assetFiles = files.filter((f) => !f.endsWith("brand-tokens.json"));
  if (!assetFiles.length && !files.some((f) => f.endsWith("brand-tokens.json"))) {
    console.log("branding/ is empty — copy Signet_Wallet_Branding_Pack here, then re-run.");
    writeTs({ logoUrl: null, markUrl: null, wordmarkUrl: null, fonts: [], tagline: null, syncedAt: null });
    writeCss(null);
    writeFontsCss(null, []);
    return;
  }

  ensureDir(OUT_DIR);
  ensureDir(path.join(OUT_DIR, "fonts"));

  const logoSrc = pickBest(files, LOGO_PATTERNS);
  const markSrc = pickBest(files, MARK_PATTERNS);
  const wordmarkSrc = pickBest(files, WORDMARK_PATTERNS);

  const manifest = {
    logoUrl: logoSrc ? copyFile(logoSrc, `logo${path.extname(logoSrc)}`) : null,
    markUrl: markSrc ? copyFile(markSrc, `mark${path.extname(markSrc)}`) : null,
    wordmarkUrl: wordmarkSrc ? copyFile(wordmarkSrc, `wordmark${path.extname(wordmarkSrc)}`) : null,
    fonts: [],
    tagline: null,
    productName: "Signet",
    syncedAt: new Date().toISOString(),
  };

  for (const f of files) {
    const ext = path.extname(f).toLowerCase();
    if (!FONT_EXT.has(ext)) continue;
    const base = path.basename(f);
    const url = copyFile(f, `fonts/${base}`);
    manifest.fonts.push({ family: path.basename(base, ext).replace(/[-_]/g, " "), url, file: base });
  }

  const tokens = readJsonTokens(files);
  if (tokens?.copy?.tagline) manifest.tagline = tokens.copy.tagline;
  if (tokens?.copy?.productName) manifest.productName = tokens.copy.productName;
  writeCss(tokens);
  writeFontsCss(tokens, manifest.fonts);
  writeTs(manifest);

  const faviconSrc = manifest.markUrl ?? manifest.logoUrl;
  if (faviconSrc) {
    const ext = path.extname(faviconSrc);
    fs.copyFileSync(path.join(ROOT, "public", faviconSrc.slice(1)), path.join(ROOT, "public", `favicon${ext}`));
  }

  console.log("Brand sync complete:");
  console.log(JSON.stringify(manifest, null, 2));
}

main();
